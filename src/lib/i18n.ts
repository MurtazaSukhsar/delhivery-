const dict: Record<Lang, Record<Key, string>> = { en, ar };

type AppKey = 'driver' | 'track';

function readLang(app: AppKey): Lang {
  try {
    const v = localStorage.getItem('th-lang-' + app);
    if (v === 'ar' || v === 'en') return v;
  } catch {
    /* ignore */
  }
  return 'en';
}

const langs: Record<AppKey, Lang> = { driver: readLang('driver'), track: readLang('track') };
const listeners = new Set<() => void>();
function setLang(app: AppKey, l: Lang) {
  langs[app] = l;
  try {
    localStorage.setItem('th-lang-' + app, l);
  } catch {
    /* ignore */
  }
  listeners.forEach((f) => f());
}

export function translate(lang: Lang, key: Key, vars?: Record<string, string | number>) {
  let s = dict[lang][key] ?? en[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
  return s;
}

export function useLang(app: AppKey) {
  const lang = useSyncExternalStore(
    (l) => (listeners.add(l), () => listeners.delete(l)),
    () => langs[app],
  );
  return {
    lang,
    dir: (lang === 'ar' ? 'rtl' : 'ltr') as 'rtl' | 'ltr',
    t: (key: Key, vars?: Record<string, string | number>) => translate(lang, key, vars),
    toggle: () => setLang(app, lang === 'ar' ? 'en' : 'ar'),
  };
}
